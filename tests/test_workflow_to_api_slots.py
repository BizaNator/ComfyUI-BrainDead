class MockObjectInfo:
    """Helper to build minimal object_info schemas for testing."""

    @staticmethod
    def make_node_schema(required_inputs, optional_inputs=None):
        schema = {"input": {"required": dict(required_inputs)}}
        if optional_inputs:
            schema["input"]["optional"] = dict(optional_inputs)
        return schema


class TestLinkResolutionByName(unittest.TestCase):
    """Verify links are resolved by input NAME, not by saved tslot index."""

    def test_link_resolved_by_name_not_tslot(self):
        """
        COB_PartsPrep_v01 scenario: BD_PartsBuilder node saves with stale tslot.
        The FIXED converter resolves by NAME, not index.

        Key point: link 22 has tslot=11 but targets input name="mask_labels".
        The converter uses NAME matching, so it correctly wires mask_labels to ["16", 1].
        The tslot value (11) is IGNORED - only the link ID and input name matter.
        """
        schema = MockObjectInfo.make_node_schema({
            "image": ["IMAGE"],
            "masks": ["MASK", {}],
            "depth_image": ["IMAGE"],
            "mask_labels": ["STRING"],
        })

        workflow = {
            "nodes": [{
                "id": 20,
                "type": "BD_PartsBuilder",
                "inputs": [
                    {"name": "image", "link": 6, "slot_index": 0},
                    {"name": "masks", "slot_index": 1},
                    {"name": "depth_image", "link": 25, "slot_index": 2},
                    {"name": "mask_labels", "link": 22, "slot_index": 11},
                ],
                "widgets_values": [],
            }],
            "links": [
                [6, 1, 0, 20, 0, "IMAGE"],
                [25, 18, 0, 20, 2, "MASK"],
                [22, 16, 1, 20, 11, "STRING"],
            ],
        }

        api = workflow_to_api(workflow, {"BD_PartsBuilder": schema})
        node_20 = api.get("20", {}).get("inputs", {})

        self.assertIn("image", node_20)
        self.assertEqual(node_20["image"], ["1", 0])
        self.assertNotIn("masks", node_20)
        self.assertIn("depth_image", node_20)
        self.assertEqual(node_20["depth_image"], ["18", 0])
        # FIXED: mask_labels IS present because link 22 targets it by NAME
        self.assertIn("mask_labels", node_20)
        self.assertEqual(node_20["mask_labels"], ["16", 1])

    def test_link_by_name_preserves_correct_wiring(self):
        """Verify that when a node reorders inputs, links still wire to correct names."""
        schema = MockObjectInfo.make_node_schema({
            "input_a": ["IMAGE"],
            "input_b": ["IMAGE"],
            "input_c": ["IMAGE"],
        })

        workflow = {
            "nodes": [{
                "id": 5,
                "type": "TestNode",
                "inputs": [
                    {"name": "input_c", "link": 3, "slot_index": 0},
                    {"name": "input_a", "link": 1, "slot_index": 1},
                    {"name": "input_b", "link": 2, "slot_index": 2},
                ],
                "widgets_values": [],
            }],
            "links": [
                [1, 10, 0, 5, 1, "IMAGE"],
                [2, 11, 0, 5, 2, "IMAGE"],
                [3, 12, 0, 5, 0, "IMAGE"],
            ],
        }

        api = workflow_to_api(workflow, {"TestNode": schema})
        node_5 = api["5"]["inputs"]

        self.assertEqual(node_5["input_a"], ["10", 0])
        self.assertEqual(node_5["input_b"], ["11", 0])
        self.assertEqual(node_5["input_c"], ["12", 0])


class TestWidgetConsumptionOrder(unittest.TestCase):
    """Verify widgets_values consumed in SCHEMA DECLARATION ORDER, not positional."""

    def test_widgets_consumed_in_schema_order(self):
        """widgets_values should be consumed in schema declaration order."""
        schema = MockObjectInfo.make_node_schema(
            required_inputs={
                "seed": ["INT", {"default": 0}],
                "steps": ["INT", {"default": 20}],
                "cfg": ["FLOAT", {"default": 7.5}],
            },
            optional_inputs={
                "optional_param": ["STRING", {"default": ""}],
            }
        )

        workflow = {
            "nodes": [{
                "id": 10,
                "type": "TestSampler",
                "inputs": [
                    {"name": "seed", "widget": {"name": "seed"}, "slot_index": 0},
                    {"name": "steps", "widget": {"name": "steps"}, "slot_index": 1},
                    {"name": "cfg", "widget": {"name": "cfg"}, "slot_index": 2},
                    {"name": "optional_param", "widget": {"name": "optional_param"}, "slot_index": 3},
                ],
                "widgets_values": [42, 30, 5.0, "test"],
            }],
            "links": [],
        }

        api = workflow_to_api(workflow, {"TestSampler": schema})
        node_10 = api["10"]["inputs"]

        self.assertEqual(node_10["seed"], 42)
        self.assertEqual(node_10["steps"], 30)
        self.assertEqual(node_10["cfg"], 5.0)
        self.assertEqual(node_10["optional_param"], "test")

    def test_widgets_with_linked_input_skip_widget_queue(self):
        """Linked inputs should NOT consume from widgets_values queue."""
        schema = MockObjectInfo.make_node_schema({
            "seed": ["INT", {"default": 0}],
            "external_model": ["MODEL"],
            "cfg": ["FLOAT", {"default": 7.5}],
        })

        workflow = {
            "nodes": [{
                "id": 15,
                "type": "TestLoader",
                "inputs": [
                    {"name": "seed", "widget": {"name": "seed"}, "slot_index": 0},
                    {"name": "external_model", "link": 99, "slot_index": 1},
                    {"name": "cfg", "widget": {"name": "cfg"}, "slot_index": 2},
                ],
                "widgets_values": [42, 7.5],
            }],
            "links": [[99, 50, 0, 15, 1, "MODEL"]],
        }

        api = workflow_to_api(workflow, {"TestLoader": schema})
        node_15 = api["15"]["inputs"]

        self.assertEqual(node_15["seed"], 42)
        self.assertEqual(node_15["external_model"], ["50", 0])
        self.assertEqual(node_15["cfg"], 7.5)


class TestDynamicComboExpansion(unittest.TestCase):
    """Verify dynamic combo sub-widgets are spliced in after their parent."""

    def test_flatten_schema_inputs_preserves_order(self):
        """flatten_schema_inputs returns inputs in declaration order."""
        schema = {
            "input": {
                "required": {
                    "req_a": ["IMAGE"],
                    "req_b": ["INT", {"default": 0}],
                },
                "optional": {
                    "opt_a": ["STRING", {"default": ""}],
                    "opt_b": ["FLOAT", {"default": 1.0}],
                }
            }
        }

        flat = flatten_schema_inputs(schema)

        self.assertEqual(len(flat), 4)
        self.assertEqual(flat[0][0], "req_a")
        self.assertEqual(flat[1][0], "req_b")
        self.assertEqual(flat[2][0], "opt_a")
        self.assertEqual(flat[3][0], "opt_b")

    def test_is_widget_type_detection(self):
        """Verify is_widget_type correctly identifies widget vs socket inputs."""
        self.assertTrue(is_widget_type(["INT", {"default": 0}]))
        self.assertTrue(is_widget_type(["FLOAT", {"default": 1.0}]))
        self.assertTrue(is_widget_type(["STRING", {"default": ""}]))
        self.assertTrue(is_widget_type(["BOOLEAN", {"default": False}]))
        self.assertTrue(is_widget_type([["option1", "option2"], {}]))

        self.assertFalse(is_widget_type(["IMAGE"]))
        self.assertFalse(is_widget_type(["MASK"]))
        self.assertFalse(is_widget_type(["MODEL"]))
        self.assertFalse(is_widget_type(["LATENT"]))


class TestRealWorkflowRegression(unittest.TestCase):
    """Regression tests against real ComfyUI workflow exports."""

    @classmethod
    def setUpClass(cls):
        cls.api_dir = tools_dir.parent / "api"
        cls.example_dir = tools_dir.parent / "example_workflows"
        cls.object_info = None

        cls.parts_builder_ui = None
        cls.parts_builder_api = None

        ui_path = cls.example_dir / "BD-parts_builder.json"
        api_path = cls.api_dir / "BD-parts_builder.api.json"

        if ui_path.exists():
            with open(ui_path) as f:
                cls.parts_builder_ui = json.load(f)

        if api_path.exists():
            with open(api_path) as f:
                cls.parts_builder_api = json.load(f)

        # Fetch object_info from running ComfyUI server
        try:
            import urllib.request
            with urllib.request.urlopen("http://127.0.0.1:8188/object_info", timeout=10) as r:
                cls.object_info = json.loads(r.read())
        except Exception:
            pass

    def test_parts_builder_node_count(self):
        """Verify converter produces same node count as ground truth."""
        if not self.parts_builder_api or not self.object_info:
            self.skipTest("BD-parts_builder.api.json or ComfyUI server not available")

        converted = workflow_to_api(self.parts_builder_ui, self.object_info)
        self.assertEqual(len(converted), len(self.parts_builder_api),
                        "Converted node count should match ground truth API export")

    def test_parts_builder_link_integrity(self):
        """Verify all links in converted output resolve to emitted nodes."""
        if not self.parts_builder_api or not self.object_info:
            self.skipTest("BD-parts_builder.api.json or ComfyUI server not available")

        converted = workflow_to_api(self.parts_builder_ui, self.object_info)
        emitted_ids = set(converted.keys())

        dangling = []
        for nid, node in converted.items():
            for inp, val in node.get("inputs", {}).items():
                if isinstance(val, list) and len(val) == 2 and isinstance(val[0], str):
                    if val[0] not in emitted_ids:
                        dangling.append((nid, inp, val[0]))

        self.assertEqual(len(dangling), 0,
                        f"Found {len(dangling)} dangling link refs: {dangling[:5]}")


