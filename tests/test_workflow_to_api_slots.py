class TestBDSAM3MultiPromptWidgetOrdering(unittest.TestCase):
    """
    Test the BD_SAM3MultiPrompt node 13 scenario from the ticket description.
    
    Ticket description states:
    "BD_SAM3MultiPrompt node 13 of the same workflow carries link 16 on prompts 
    while widgets_values[0] is still the prompt text. Consuming the queue only 
    for unlinked inputs read every later widget one slot early."
    
    This tests that linked inputs don't skip widget values for subsequent inputs.
    """

    def test_bd_sam3_multi_prompt_widget_order(self):
        """BD_SAM3MultiPrompt: linked 'prompts' input should not shift widget values."""
        # Simplified schema mimicking BD_SAM3MultiPrompt
        schema = MockObjectInfo.make_node_schema({
            "prompts": ["STRING"],  # Linked input
            "negative_prompts": ["STRING", {"default": ""}],  # Widget
            "combine_mode": ["STRING", {"default": "union"}],  # Widget  
            "vote_threshold": ["FLOAT", {"default": 0.5}],  # Widget
        })

        # Simulating: link 16 on prompts, widgets_values = ["my prompt", "neg", "union", 0.7]
        # OLD BUG: Reading widgets_values only for unlinked inputs would shift everything
        # FIXED: Linked inputs skip widget slot, widgets consumed in order
        workflow = {
            "nodes": [{
                "id": 13,
                "type": "BD_SAM3MultiPrompt",
                "inputs": [
                    {"name": "prompts", "link": 16, "slot_index": 0},
                    {"name": "negative_prompts", "widget": {"name": "negative_prompts"}, "slot_index": 1},
                    {"name": "combine_mode", "widget": {"name": "combine_mode"}, "slot_index": 2},
                    {"name": "vote_threshold", "widget": {"name": "vote_threshold"}, "slot_index": 3},
                ],
                "widgets_values": ["negative_text", "union", 0.7],  # prompts is linked, so only 3 widget values
            }],
            "links": [[16, 10, 0, 13, 0, "STRING"]],
        }

        api = workflow_to_api(workflow, {"BD_SAM3MultiPrompt": schema})
        node_13 = api["13"]["inputs"]

        # prompts gets the link
        self.assertEqual(node_13["prompts"], ["10", 0])
        # negative_prompts gets first widget value (NOT shifted)
        self.assertEqual(node_13["negative_prompts"], "negative_text")
        # combine_mode gets second widget value
        self.assertEqual(node_13["combine_mode"], "union")
        # vote_threshold gets third widget value
        self.assertEqual(node_13["vote_threshold"], 0.7)


class TestBDPartsExportBaseImageWidget(unittest.TestCase):
    """
    Test BD_PartsExport.base_image arriving as boolean True bug.
    
    Ticket description states:
    "Same cause behind BD_PartsExport.base_image arriving as the boolean True: 
    its link was dropped, so the widget queue filled the input instead."
    
    This tests that when a link is dropped, the widget value correctly fills the slot.
    """

    def test_bd_parts_export_base_image_widget_fallback(self):
        """BD_PartsExport: dropped link means widget value fills the slot."""
        schema = MockObjectInfo.make_node_schema({
            "parts_bundle": ["PARTS_BUNDLE"],
            "base_image": ["IMAGE", {}],  # Optional, may be linked or widget
            "filename": ["STRING", {"default": "output"}],
        })

        # base_image link was dropped (tslot out of range), widget True fills the slot
        workflow = {
            "nodes": [{
                "id": 30,
                "type": "BD_PartsExport",
                "inputs": [
                    {"name": "parts_bundle", "link": 30, "slot_index": 0},
                    {"name": "base_image", "slot_index": 1},  # Link dropped, will use widget
                    {"name": "filename", "widget": {"name": "filename"}, "slot_index": 2},
                ],
                "widgets_values": [True, "my_output.png"],  # base_image=True, filename="my_output.png"
            }],
            "links": [[30, 20, 0, 30, 0, "PARTS_BUNDLE"]],
        }

        api = workflow_to_api(workflow, {"BD_PartsExport": schema})
        node_30 = api["30"]["inputs"]

        self.assertEqual(node_30["parts_bundle"], ["20", 0])
        # base_image gets widget value True (the bug was this being True instead of an image link)
        self.assertEqual(node_30["base_image"], True)
        self.assertEqual(node_30["filename"], "my_output.png")


